#!/usr/bin/env bash
# Regenerates app/assets/licenses/go.txt: the license of every Go module linked
# into the native library and the browser engine, shown in Settings → Open-source licenses.
set -euo pipefail

repo="$(cd "$(dirname "$0")/.." && pwd)"
output="$repo/app/assets/licenses/go.txt"
go_licenses=(mise exec go:github.com/google/go-licenses/v2@2.0.1 -- go-licenses)
separator='--------------------------------------------------------------------------------'

work="$(mktemp -d "${TMPDIR:-/tmp}/cryptdrive-licenses.XXXXXX")"
trap 'rm -r "$work"' EXIT
cat >"$work/entry.tpl" <<EOF
{{range .}}{{.Name}}
{{.LicenseText}}
$separator
{{end}}
EOF

cd "$repo/native"
"${go_licenses[@]}" report . --ignore github.com/Its-Alex --template "$work/entry.tpl" >"$work/native.txt" 2>/dev/null
GOOS=js GOARCH=wasm "${go_licenses[@]}" report ./wasm --ignore github.com/Its-Alex --template "$work/entry.tpl" >"$work/wasm.txt" 2>/dev/null

mkdir -p "$(dirname "$output")"
python3 - "$work/native.txt" "$work/wasm.txt" "$(go env GOROOT)/LICENSE" "$output" "$separator" <<'PY'
import sys
native, wasm, goroot_license, output, separator = sys.argv[1:]
entries = {}
for path in (native, wasm):
    for chunk in open(path).read().split(separator + '\n'):
        chunk = chunk.strip('\n')
        if chunk:
            name, _, text = chunk.partition('\n')
            entries[name] = text.strip('\n')
entries['Go (standard library and runtime)'] = open(goroot_license).read().strip('\n')
with open(output, 'w') as out:
    out.write('# Generated by tools/generate-licenses.sh: re-run it, do not edit.\n' + separator + '\n')
    for name in sorted(entries, key=str.lower):
        out.write(f'{name}\n\n{entries[name]}\n{separator}\n')
PY
echo "$output: $(grep -c -- "^$separator\$" "$output") entries"
